function parseGloss(raw) {
  const map = Object.create(null);
  for (const line of raw.split('\n')) {
    const tab = line.indexOf('\t');
    if (tab <= 0) continue;
    map[line.slice(0, tab)] = line.slice(tab + 1);
  }
  return map;
}

export const WORD_GLOSS = parseGloss(RAW);

export function glossToken(token) {
  const endsSentence = /[.]$/.test(token);
  const key = String(token).replace(/[.,]/g, '').toLowerCase();
  const gloss = WORD_GLOSS[key] || key;
  return endsSentence ? `${gloss}。` : gloss;
}

export function glossWords(words) {
  return words.map((token) => glossToken(token));
}
