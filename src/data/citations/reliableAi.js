export function citationsForChapter(chapter) {
  return CITATIONS.filter((c) => c.chapter === chapter);
}

export function citationsForDeck(deckId) {
  const deck = DECKS.find((d) => d.id === deckId);
  return deck ? citationsForChapter(deck.chapter) : [];
}

export function citationById(id) {
  return CITATIONS.find((c) => c.id === id) || null;
}

export function formatCitation(c) {
  const year = c.year ? ` (${c.year})` : ' (n.d.)';
  return `${c.author}${year}. ${c.title}. ${c.publisher}.`;
}
