/**
 * Dedicated sidebar config for the 'fundamentals' docs plugin instance only
 * (see docusaurus.config.mjs / docPlugins.mjs).
 *
 * Respects DOC_FUND_ONLY / DOC_FUND_EXCLUDE so binary-search builds don't
 * leave empty categories (Docusaurus errors on categories with no items).
 */

// @ts-check

/**
 * @param {string | undefined} raw
 * @returns {Set<string>}
 */
function parseIdList(raw) {
  return new Set(
    String(raw || '')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean),
  );
}

/**
 * @returns {Set<string> | null} null = all folders kept
 */
function keptFolderSet() {
  const only = parseIdList(process.env.DOC_FUND_ONLY);
  const excl = parseIdList(process.env.DOC_FUND_EXCLUDE);
  if (only.size === 0 && excl.size === 0) {
    return null;
  }
  const all = [
    'algorithms',
    'artificial-intelligence',
    'computer-engineering',
    'electronics',
    'finance',
    'game-engine-development',
    'graphics',
    'math-and-science',
    'scalable-systems',
  ];
  if (only.size > 0) {
    return new Set(all.filter((f) => only.has(f)));
  }
  return new Set(all.filter((f) => !excl.has(f)));
}

/**
 * @param {string} folder
 * @param {Set<string> | null} kept
 */
function includeFolder(folder, kept) {
  return kept === null || kept.has(folder);
}

const kept = keptFolderSet();

/** @type {import('@docusaurus/plugin-content-docs').SidebarsConfig} */
const sidebars = {};

/** @type {Array<{folder: string, label: string}>} */
const tutorialCategories = [
  {folder: 'artificial-intelligence', label: 'Artificial Intelligence'},
  {folder: 'computer-engineering', label: 'Computer Engineering'},
  {folder: 'algorithms', label: 'Algorithms'},
  {folder: 'game-engine-development', label: 'Game Engine'},
  {folder: 'graphics', label: 'Graphics'},
  {folder: 'scalable-systems', label: 'Scalable Systems'},
];

const tutorialItems = tutorialCategories
  .filter((c) => includeFolder(c.folder, kept))
  .map((c) => ({
    type: /** @type {'category'} */ ('category'),
    label: c.label,
    items: [{type: /** @type {'autogenerated'} */ ('autogenerated'), dirName: c.folder}],
  }));

if (tutorialItems.length > 0) {
  sidebars.tutorialSidebar = tutorialItems;
}

/** Isolated sidebars — only register when that folder is included. */
if (includeFolder('math-and-science', kept)) {
  sidebars.mathAndScienceSidebar = [
    {type: 'autogenerated', dirName: 'math-and-science'},
  ];
}
if (includeFolder('electronics', kept)) {
  sidebars.electronicsSidebar = [
    {type: 'autogenerated', dirName: 'electronics'},
  ];
}
if (includeFolder('finance', kept)) {
  sidebars.financeSidebar = [{type: 'autogenerated', dirName: 'finance'}];
}

// Docusaurus requires at least one sidebar key; if everything is filtered out,
// provide an empty autogenerated root so the plugin can still load.
if (Object.keys(sidebars).length === 0) {
  sidebars.tutorialSidebar = [{type: 'autogenerated', dirName: '.'}];
}

module.exports = sidebars;
